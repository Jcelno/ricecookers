import assert from "node:assert/strict";
import puppeteer from "puppeteer";
const base = process.env.RADIUM_TEST_URL ?? "http://localhost:3000";
const browser = await puppeteer.launch({ headless: true, args: ["--ignore-gpu-blocklist", "--enable-webgl", "--use-angle=metal", "--enable-unsafe-swiftshader"] });
try {
  const page = await browser.newPage();
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.setViewport({ width: 390, height: 844 });
  await page.goto(`${base}/?tour=0`);
  await page.waitForFunction(() => !!window.__radium?.getState().meta);
  await page.evaluate(() => { const s = window.__radium.getState(); s.setBody("earth"); s.setPanel("left", false); s.setPanel("right", false); });
  await page.waitForFunction(() => !!window.__maplibre);
  await page.evaluate(() => window.__maplibre.jumpTo({ center: [-69.5, -24.5], zoom: 5 }));
  const before = await page.evaluate(() => ({ center: window.__maplibre.getCenter().toArray(), zoom: window.__maplibre.getZoom() }));
  await page.click('[aria-label^="Satellite imagery:"]');
  const popup = await page.$eval("#quick-layer-popover", el => { const r = el.getBoundingClientRect(); return { left: r.left, right: r.right }; });
  assert(popup.left >= 0 && popup.right <= 390, "map popover fits mobile");
  await page.evaluate(() => [...document.querySelectorAll('#quick-layer-popover [role="radio"]')].find(el => el.textContent.includes("Esri World Imagery")).click());
  await page.waitForFunction(() => window.__maplibre?.getMaxZoom() === 17 && window.__maplibre.isStyleLoaded());
  const after = await page.evaluate(() => ({ center: window.__maplibre.getCenter().toArray(), zoom: window.__maplibre.getZoom(), attribution: window.__maplibre.getStyle().sources.base.attribution }));
  assert.deepEqual(after.center, before.center, "base source switch preserves camera center");
  assert.equal(after.zoom, before.zoom, "base source switch preserves zoom");
  assert.match(after.attribution, /Esri.*Earthstar/);
  assert.equal(await page.$("#quick-layer-popover"), null, "picking a source closes the popover");
  await page.click('[aria-label^="Data layer:"]');
  await page.evaluate(() => [...document.querySelectorAll('#quick-layer-popover [role="radio"]')].find(el => /slope/i.test(el.textContent)).click());
  await page.waitForFunction(() => /slope/.test(window.__radium.getState().layers.earth.overlay?.id ?? ""));
  assert.equal(await page.$("#quick-layer-popover"), null);
  await page.click('[aria-label^="Data layer:"]');
  await page.focus('[aria-label="Quick data layer opacity"]');
  await page.keyboard.press("Home");
  await page.waitForFunction(() => window.__radium.getState().layers.earth.opacity === .2 && window.__maplibre.getPaintProperty("ov", "raster-opacity") === .2);
  await page.keyboard.press("Escape");
  assert.equal(await page.$("#quick-layer-popover"), null, "Escape closes the menu");
  await page.click(".quick-boundaries");
  await page.waitForFunction(() => window.__maplibre.getLayoutProperty("boundary", "visibility") === "none");
  assert.equal(await page.evaluate(() => window.__maplibre.getLayoutProperty("label-country", "visibility")), "visible", "borders toggle does not hide place names");
  await page.click('[aria-label^="Data layer:"]');
  await page.evaluate(() => [...document.querySelectorAll('#quick-layer-popover button')].find(el => el.textContent.includes("Turn off layer")).click());
  await page.waitForFunction(() => !window.__radium.getState().layers.earth.overlay && !window.__maplibre.getLayer("ov"));
  await page.click('[aria-label^="Satellite imagery:"]');
  await page.mouse.click(20, 500);
  assert.equal(await page.$("#quick-layer-popover"), null, "click-away closes the menu");
  assert.deepEqual(errors, []);
  console.log("PASS mobile map pills, Esri source/zoom/attribution, camera preservation, shared opacity, independent boundaries, menu dismissal");
} finally { await browser.close(); }
