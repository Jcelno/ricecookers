import assert from "node:assert/strict";
import puppeteer from "puppeteer";
const browser = await puppeteer.launch({ headless: true, args: ["--ignore-gpu-blocklist", "--enable-webgl", "--use-angle=metal", "--enable-unsafe-swiftshader"] });
try {
  const page = await browser.newPage();
  await page.setViewport({ width: 1440, height: 900 });
  await page.goto(`${process.env.RADIUM_TEST_URL ?? "http://localhost:3000"}/?tour=0`);
  await page.waitForSelector('[data-tour="help"]');
  await page.keyboard.press("/");
  await page.waitForFunction(() => document.activeElement.matches('input[role="combobox"]'));
  await page.keyboard.type("123Lstc");
  assert.equal(await page.evaluate(() => window.__radium.getState().body), "moon", "typing does not trigger shortcuts");
  await page.keyboard.press("Escape");
  assert.equal(await page.$eval('input[role="combobox"]', el => el.value), "");
  await page.keyboard.press("2");
  await page.waitForFunction(() => window.__radium.getState().body === "mars");
  const panel = await page.evaluate(() => window.__radium.getState().leftOpen);
  await page.keyboard.press("l");
  assert.equal(await page.evaluate(() => window.__radium.getState().leftOpen), !panel);
  await page.keyboard.press("/");
  await page.waitForFunction(() => document.activeElement.matches('input[role="combobox"]'));
  await page.keyboard.type("-5.44, 137.7");
  await page.waitForSelector('[role="option"]');
  await page.keyboard.press("Enter");
  await page.keyboard.press("Escape");
  await page.waitForFunction(() => window.__radium.getState().cellStatus === "ready");
  await page.keyboard.press("s");
  await page.keyboard.press("c");
  assert.equal(await page.evaluate(() => window.__radium.getState().saved.sites.length), 1);
  assert.equal(await page.evaluate(() => window.__radium.getState().compareList.length), 1);
  await page.keyboard.press("t");
  await page.waitForFunction(() => window.__radium.getState().twinStatus === "ready", { timeout: 30000 });
  await page.keyboard.press("?");
  await page.waitForFunction(() => [...document.querySelectorAll('[role="dialog"]')].some(el => el.textContent.includes("Keyboard shortcuts")));
  await page.keyboard.press("1");
  assert.equal(await page.evaluate(() => window.__radium.getState().body), "mars", "modal suppresses single-key navigation");
  await page.keyboard.press("Escape");
  await page.waitForFunction(() => ![...document.querySelectorAll('[role="dialog"]')].some(el => el.textContent.includes("Keyboard shortcuts")));
  await page.setViewport({ width: 390, height: 844 });
  await page.evaluate(() => document.activeElement.blur());
  await page.keyboard.press("2");
  await page.waitForSelector('input[role="combobox"]');
  await page.keyboard.press("/");
  await page.waitForFunction(() => document.activeElement.matches('input[role="combobox"]'));
  assert(await page.evaluate(() => { const el = document.activeElement; const r = el.getBoundingClientRect(); return el.matches('input[role="combobox"]') && r.width > 0 && r.right <= innerWidth; }), "mobile search opens when focused by shortcut");
  console.log("PASS real keyboard actions, typing/modal guards, selection context and mobile search");
} finally { await browser.close(); }
